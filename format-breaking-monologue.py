TERMINATION_COMMAND = "\u0005End File\u0006"

def write_stdout(text: str) -> None:
    print(text, flush=True)

def write_stderr(text: str) -> None:
    print(text, file=stderr, flush=True)

CACHE_CONTROL_EPHEMERAL_5M: Final[CacheControlEphemeralParam] = CacheControlEphemeralParam(
    type="ephemeral",
    ttl="5m",
)
"""Cache control marker for the Anthropic API denoting a 5-minute token cache."""

CACHE_CONTROL_EPHEMERAL_1H: Final[CacheControlEphemeralParam] = CacheControlEphemeralParam(
    type="ephemeral",
    ttl="1h",
)
"""Cache control marker for the Anthropic API denoting a 1-hour token cache."""

CHUNK_ID_LENGTH: Final[int] = 16
CHUNK_ID_ALPHABET: Final[tuple[str]] = tuple(map(chr, chain(range(ord("a"), (ord("z")+1)), range(ord("0"), (ord("9")+1)))))

def generate_chunk_id():
    return "".join(random_choices(CHUNK_ID_ALPHABET, k=CHUNK_ID_LENGTH))

class Chunk(PydanticBaseModel):
    id: str
    previous_chunk_id: Optional[str] = None
    branch_count: int = 0
    role: (Literal["system"] | Literal["user"] | Literal["assistant"])
    text: str
    status: (Literal["prefilled"] | Literal["processing"] | Literal["succeeded"] | Literal["errored"] | Literal["expired"] | Literal["canceled"])
    error: Optional[AnthropicErrorObject] = None
    stop_reason: Optional[StopReason] = None
    stop_sequence: Optional[str] = None
    usage: Optional[Usage] = None
    cost: float = 0.0
    end_turn_count: int = 0

chunks_by_id: Final[dict[str, Chunk]] = dict()
chunks_by_creation_time: Final[list[Chunk]] = list()

root_chunk: Optional[Chunk] = None
for chunk_param in INITIAL_CHUNK_PARAMS:
    chunk_id: str = generate_chunk_id()
    chunk: Final[Chunk] = Chunk(
        id=chunk_id,
        previous_chunk_id=(None if not root_chunk else root_chunk.id),
        role=chunk_param["role"],
        text=chunk_param["text"],
        status="prefilled",
    )
    chunks_by_id[chunk_id] = chunk
    chunks_by_creation_time.append(chunk)
    if root_chunk:
        root_chunk.branch_count += 1
    root_chunk = chunk

def content_to_str(content: (str | list[ContentBlock])) -> str:
    return (
        content if isinstance(content, str)
        else "".join(
            (
                content_block.text if content_block.type == "text"
                else f"[unhandled content type: {content_block.type}]"
            ) for content_block in content
        )
    ).rstrip()

def create_assistant_chunk(previous_chunk_id: Optional[str] = None) -> Chunk:
    chunk_id = generate_chunk_id()
    chunk = Chunk(
        id=chunk_id,
        previous_chunk_id=previous_chunk_id,
        role="assistant",
        text="",
        status="processing",
    )
    chunks_by_id[chunk_id] = chunk
    chunks_by_creation_time.append(chunk)
    if previous_chunk_id:
        chunks_by_id[previous_chunk_id].branch_count += 1
        write_stderr(f"Branching from chunk id={previous_chunk_id}, branch_count={chunks_by_id[previous_chunk_id].branch_count}")
    write_stderr(f"Created chunk: id={chunk_id}, status=processing")
    return chunk

def calculate_cost(usage: Usage) -> float:
    cost: float = 0.0
    cost += (COST_PER_TOKEN_INPUT * usage.input_tokens) + (COST_PER_TOKEN_OUTPUT * usage.output_tokens)
    cache_read_tokens = usage.cache_read_input_tokens
    if cache_read_tokens:
        cost += (COST_PER_TOKEN_CACHE_READ * cache_read_tokens)
    cache_creation = usage.cache_creation
    if cache_creation:
        cost += (COST_PER_TOKEN_CACHE_WRITE_5M * cache_creation.ephemeral_5m_input_tokens) + (COST_PER_TOKEN_CACHE_WRITE_1H * cache_creation.ephemeral_1h_input_tokens)
    return cost

def update_chunk_from_message_batch_response(response: MessageBatchIndividualResponse) -> Chunk:
    chunk_id: Final[str] = response.custom_id
    chunk: Final[Chunk] = chunks_by_id[chunk_id]
    result: Final[MessageBatchResult] = response.result
    result_type: Final[str] = result.type
    chunk.status = result_type
    if result_type == "succeeded":
        message: Final[Message] = result.message
        chunk.text = content_to_str(message.content)
        chunk.stop_reason = message.stop_reason
        chunk.stop_sequence = message.stop_sequence
        if chunk.stop_reason == "end_turn":
            chunk.text += END_TURN_PLACEHOLDER
            chunk.end_turn_count = chunks_by_id[chunk.previous_chunk_id].end_turn_count + 1
        elif chunk.stop_reason == "stop_sequence":
            chunk.text += chunk.stop_sequence
        chunk.usage = message.usage
        chunk.cost = 0.0 if not chunk.usage else calculate_cost(chunk.usage)
    elif result_type == "errored":
        chunk.error = result.error.error
    write_stderr(f"Updated chunk: id={chunk_id}, status={result_type}")
    return chunk

def chunk_to_message_create_params(chunk: Chunk) -> MessageCreateParamsNonStreaming:
    system: list[TextBlock] = []
    messages: list[MessageParam] = []
    current_chunk = chunk
    while True:
        status = current_chunk.status
        if not (status == "prefilled" or status == "succeeded"): raise Error(f"Can't generate MessageCreateParams for chunk [{current_chunk.id}] because its status is \"{status}\"")
        role = current_chunk.role
        text = current_chunk.text
        if role == "system":
            system.insert(0, TextBlockParam(
                type="text",
                text=text,
            ))
        else:
            if messages and (messages[0]["role"] == role):
                message = messages[0]
            else:
                message = MessageParam(
                    role=role,
                    content=[],
                )
                messages.insert(0, message)
            message["content"].insert(0, TextBlockParam(
                type="text",
                text=text,
            ))
        previous_chunk_id = current_chunk.previous_chunk_id
        if not previous_chunk_id: break
        current_chunk = chunks_by_id[previous_chunk_id]
    if messages and messages[-1]["content"]:
        messages[-1]["content"][-1]["cache_control"] = CACHE_CONTROL_EPHEMERAL_1H
    elif system:
        system[-1]["cache_control"] = CACHE_CONTROL_EPHEMERAL_1H
    return MessageCreateParamsNonStreaming(
        model=MODEL,
        temperature=TEMPERATURE,
        max_tokens=MAX_OUTPUT_TOKENS_PER_REQUEST,
        system=system,
        messages=messages,
        stop_sequences=[ TERMINATION_COMMAND ],
    )

def create_batch_create_request_for_chunk(chunk: Chunk) -> MessageBatchCreateRequest:
    new_chunk: Final[Chunk] = create_assistant_chunk(chunk.id)
    return MessageBatchCreateRequest(
        custom_id=new_chunk.id,
        params=chunk_to_message_create_params(chunk),
    )

anthropic = AsyncAnthropic()

async def submit_message_batch_and_poll_until_completion(requests: list[MessageBatchCreateRequest]) -> list[Chunk]:
    write_stderr(f"Submitting a message batch with {len(requests)} requests...")
    batch = await anthropic.messages.batches.create(requests=requests)
    batch_id = batch.id
    write_stderr(f"Submitted message batch [{batch_id}]")
    while batch.processing_status != "ended":
        write_stderr(f"Sleeping for {MESSAGE_BATCH_POLL_INTERVAL} seconds")
        await asyncio_sleep(MESSAGE_BATCH_POLL_INTERVAL)
        write_stderr(f"Checking status of message batch [{batch_id}]")
        batch = await anthropic.messages.batches.retrieve(batch_id)
        write_stderr(batch.request_counts.model_dump_json())
    write_stderr(f"\aMessage batch [{batch_id}] finished processing; fetching results...")
    new_chunks = []
    async for response in await anthropic.messages.batches.results(batch_id):
        chunk = update_chunk_from_message_batch_response(response)
        write_stdout(chunk.model_dump_json(indent=2))
        new_chunks.append(chunk)
    write_stderr(f"Finished processing message batch [{batch_id}]")
    return new_chunks

async def main():
    total_cost: float = 0.0
    total_requests: int = 0

    write_stdout("\n".join(chunk.model_dump_json(indent=2) for chunk in chunks_by_creation_time))

    # To ensure cost-efficient use of the cache, we start by submitting
    # a single message request. When a batch finishes, we generate new
    # completions for the most recent chunks which have less than
    # `MAX_BRANCHES_PER_CHUNK` branches. This ensures that every
    # completion (after the first) re-uses an existing prefix.

    while True:
        chunks_to_continue: list[Chunk] = list(islice(
            (chunk for chunk in reversed(chunks_by_creation_time) if (
                chunk.status == "succeeded"
                and (chunk.stop_reason == "max_tokens" or chunk.stop_reason == "pause_turn" or chunk.stop_reason == "end_turn" or (chunk.stop_reason == "stop_sequence" and chunk.stop_sequence == END_TURN_PLACEHOLDER))
                and chunk.branch_count < MAX_BRANCHES_PER_CHUNK
                and chunk.end_turn_count < MAX_END_TURN_COUNT
            )),
            MAX_REQUESTS_PER_BATCH
        ))
        if len(chunks_to_continue) < MAX_REQUESTS_PER_BATCH:
            if root_chunk.branch_count == 0:
                # Start with a single request, to get the root chunk into the cache.
                chunks_to_continue.append(root_chunk)
            elif root_chunk.branch_count < MAX_BRANCHES_FROM_ROOT:
                for n in range(0, min(MAX_REQUESTS_PER_BATCH, (MAX_BRANCHES_FROM_ROOT - root_chunk.branch_count))):
                    chunks_to_continue.append(root_chunk)
        if not chunks_to_continue:
            write_stderr("Stopping because all threads have terminated.")
            break
        new_chunks: list[Chunk] = await submit_message_batch_and_poll_until_completion(list(map(create_batch_create_request_for_chunk, chunks_to_continue)))
        batch_cost: float = sum(chunk.cost for chunk in new_chunks)
        total_cost += batch_cost
        write_stderr(f"Last batch cost: {batch_cost}\nTotal cost: {total_cost}")
        if total_cost >= MAX_COST_PER_SESSION:
            write_stderr(f"Stopping because total cost has exceeded the threshold of ${MAX_COST_PER_SESSION}.")
            break

asyncio_run(main())
